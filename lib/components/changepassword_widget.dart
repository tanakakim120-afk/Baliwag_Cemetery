            fontWeight: FontWeight.w500,
          ),
        ),
      ],
    );
  }

  // Validation method
  bool _validateFields() {
    // Check if all fields have values
    if (_model.textController1.text.trim().isEmpty) {
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(content: Text('❌ Username is required')),
      );
      return false;
    }

    if (_model.textController2.text.trim().isEmpty) {
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(content: Text('❌ Email is required')),
      );
      return false;
    }

    if (_model.currentPasswordController.text.trim().isEmpty) {
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(content: Text('❌ Current password is required')),
      );
      return false;
    }

    if (_model.newPasswordController.text.trim().isEmpty) {
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(content: Text('❌ New password is required')),
      );
      return false;
    }

    if (_model.confirmPasswordController.text.trim().isEmpty) {
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(content: Text('❌ Please confirm your new password')),
      );
      return false;
    }

    // Check password format
    final passwordRegex = RegExp(
        r'^(?=.*[a-z])(?=.*[A-Z])(?=.*\d)(?=.*[@$!%*?&])[A-Za-z\d@$!%*?&]{8,}$');
    if (!passwordRegex.hasMatch(_model.newPasswordController.text)) {
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(
            content: Text(
                '❌ Password must be 8+ chars with uppercase, lowercase, digit, and special character')),
      );
      return false;
    }

    // Check if passwords match
    if (_model.newPasswordController.text !=
        _model.confirmPasswordController.text) {
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(content: Text('❌ Passwords do not match')),
      );
      return false;
    }

    // Check if new password is different from current
    if (_model.currentPasswordController.text ==
        _model.newPasswordController.text) {
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(
            content:
                Text('❌ New password must be different from current password')),
      );
      return false;
    }

    return true;
  }

