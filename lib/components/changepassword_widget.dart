  // Password strength calculation
  int getPasswordStrength(String password) {
    int strength = 0;
    if (password.length >= 8) strength++;
    if (password.contains(RegExp(r'[a-z]'))) strength++;
    if (password.contains(RegExp(r'[A-Z]'))) strength++;
    if (password.contains(RegExp(r'[0-9]'))) strength++;
    if (password.contains(RegExp(r'[@$!%*?&]'))) strength++;
    return strength;
  }

  // Password strength indicator widget
  Widget _buildPasswordStrengthIndicator(String password) {
    final strength = getPasswordStrength(password);
    Color color;
    String label;

    if (strength <= 2) {
      color = Color(0xFFDC2626); // Red
      label = 'Weak';
    } else if (strength <= 3) {
      color = Color(0xFFF59E0B); // Orange
      label = 'Medium';
    } else {
      color = Color(0xFF10B981); // Green
      label = 'Strong';
    }

    return Row(
      children: [
        Text(
          'Strength: ',
          style: GoogleFonts.inter(fontSize: 12, color: Color(0xFF6B7280)),
        ),
        Expanded(
          child: Row(
            children: List.generate(5, (index) {
              return Container(
                margin: EdgeInsets.only(right: 4),
                height: 4,
                width: 20,
                decoration: BoxDecoration(
                  color: index < strength ? color : Color(0xFFE5E7EB),
                  borderRadius: BorderRadius.circular(2),
                ),
              );
            }),
          ),
        ),
        Text(
          label,
          style: GoogleFonts.inter(
            fontSize: 12,
            color: color,
            fontWeight: FontWeight.w600,
          ),
        ),
      ],
    );
  }

  // Password match indicator widget
  Widget _buildPasswordMatchIndicator() {
    final passwordsMatch = _model.newPasswordController.text ==
        _model.confirmPasswordController.text;
    final hasConfirmPassword = _model.confirmPasswordController.text.isNotEmpty;

    if (!hasConfirmPassword) return SizedBox.shrink();

    return Row(
      children: [
        Icon(
          passwordsMatch ? Icons.check_circle : Icons.error,
          color: passwordsMatch ? Color(0xFF10B981) : Color(0xFFDC2626),
          size: 16,
